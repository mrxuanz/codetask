#!/usr/bin/env node

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { format } from 'prettier'

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const outputPath = resolve(repositoryRoot, 'THIRD_PARTY_DEPENDENCIES.md')

function dependencyName(packagePath, metadata) {
  if (typeof metadata.name === 'string' && metadata.name) return metadata.name
  const marker = 'node_modules/'
  const packageIndex = packagePath.lastIndexOf(marker)
  const relative = packagePath.slice(packageIndex + marker.length)
  const parts = relative.split('/')
  return relative.startsWith('@') ? parts.slice(0, 2).join('/') : parts[0]
}

function declaredLicense(manifest) {
  if (typeof manifest?.license === 'string' && manifest.license.trim()) {
    return manifest.license.trim()
  }
  if (manifest?.license && typeof manifest.license.type === 'string') {
    return manifest.license.type
  }
  if (Array.isArray(manifest?.licenses)) {
    const values = manifest.licenses
      .map((item) => (typeof item === 'string' ? item : item?.type))
      .filter((item) => typeof item === 'string' && item.trim())
    if (values.length) return values.join(' OR ')
  }
  return undefined
}

export function dependencyLicense(packagePath, lockMetadata = {}) {
  const lockedLicense = declaredLicense(lockMetadata)
  if (lockedLicense) return lockedLicense

  const manifestPath = resolve(repositoryRoot, packagePath, 'package.json')
  if (!existsSync(manifestPath)) return 'UNKNOWN'
  try {
    const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
    return declaredLicense(manifest) ?? 'UNKNOWN'
  } catch {
    // Keep the package in the report even if its installed manifest is unreadable.
  }
  return 'UNKNOWN'
}

export function npmDependencies() {
  const lock = JSON.parse(readFileSync(resolve(repositoryRoot, 'package-lock.json'), 'utf8'))
  const unique = new Map()
  for (const [packagePath, metadata] of Object.entries(lock.packages ?? {})) {
    if (!packagePath.includes('node_modules/') || metadata.link || !metadata.version) continue
    const name = dependencyName(packagePath, metadata)
    const key = `${name}@${metadata.version}`
    if (!unique.has(key)) {
      unique.set(key, {
        name,
        version: metadata.version,
        license: dependencyLicense(packagePath, metadata)
      })
    }
  }
  return [...unique.values()].sort((left, right) =>
    `${left.name}@${left.version}`.localeCompare(`${right.name}@${right.version}`)
  )
}

export function cargoDependencies() {
  const lock = readFileSync(resolve(repositoryRoot, 'native/Cargo.lock'), 'utf8')
  const dependencies = []
  for (const block of lock.split('\n[[package]]\n').slice(1)) {
    const name = block.match(/^name = "([^"]+)"/m)?.[1]
    const version = block.match(/^version = "([^"]+)"/m)?.[1]
    const source = block.match(/^source = "([^"]+)"/m)?.[1]
    if (name && version && source) dependencies.push({ name, version, source })
  }
  return dependencies.sort((left, right) =>
    `${left.name}@${left.version}`.localeCompare(`${right.name}@${right.version}`)
  )
}

export function assertKnownNpmLicenses(dependencies) {
  const unknown = dependencies.filter((dependency) => dependency.license === 'UNKNOWN')
  if (unknown.length) {
    throw new Error(
      `Unresolved npm dependency licenses:\n${unknown
        .map((dependency) => `- ${dependency.name}@${dependency.version}`)
        .join('\n')}`
    )
  }
}

export function renderReport() {
  const npm = npmDependencies()
  const cargo = cargoDependencies()
  assertKnownNpmLicenses(npm)
  return [
    '# Third-party dependency inventory',
    '',
    '<!-- Generated by scripts/ci/generate-third-party-dependencies.mjs. Do not edit by hand. -->',
    '',
    'This inventory is generated from the committed npm and Cargo lockfiles. npm license labels come from lockfile metadata with installed package manifests as a fallback. Generation fails if any npm license remains unresolved.',
    '',
    `## npm (${npm.length})`,
    '',
    '| Package | Version | Declared license |',
    '| --- | --- | --- |',
    ...npm.map(
      (dependency) =>
        `| ${dependency.name.replaceAll('|', '\\|')} | ${dependency.version} | ${dependency.license.replaceAll('|', '\\|')} |`
    ),
    '',
    `## Cargo (${cargo.length})`,
    '',
    '| Crate | Version | Locked source |',
    '| --- | --- | --- |',
    ...cargo.map(
      (dependency) =>
        `| ${dependency.name} | ${dependency.version} | ${dependency.source.replaceAll('|', '\\|')} |`
    ),
    ''
  ].join('\n')
}

async function main() {
  const report = await format(renderReport(), { parser: 'markdown' })
  if (process.argv.includes('--check')) {
    if (!existsSync(outputPath) || readFileSync(outputPath, 'utf8') !== report) {
      console.error(
        'THIRD_PARTY_DEPENDENCIES.md is stale; run npm run generate:third-party-dependencies'
      )
      process.exit(1)
    }
    console.log('Third-party dependency inventory is current')
  } else {
    writeFileSync(outputPath, report)
    console.log(`Wrote ${outputPath}`)
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  await main()
}
